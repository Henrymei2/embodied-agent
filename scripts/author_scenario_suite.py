"""Author the EmbodiedAgentBench scenario suite and freeze its held-out split.

The scenarios live here as explicit records rather than in a generator loop.
A benchmark built by templating one scenario a hundred times measures one
scenario a hundred times, and the resulting number looks like coverage while
answering a single question. Every entry below names its own task, its own
terminal predicates, and its own forbidden effects.

Splits are assigned per scenario and are deliberately not random: each
capability area contributes to development, validation, and held-out, so the
frozen split exercises the whole system rather than whichever areas a shuffle
happened to land on.

Run with `--write` to emit the suite and its frozen digest.
"""

