def build():
    suite = suite_from_records(SUITE_REVISION, SCENARIOS)
    suite.validate()
    return suite


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write the suite file")
    args = parser.parse_args()

    suite = build()
    coverage = suite.coverage()
    payload = {
        "schema_version": SCENARIO_SCHEMA_VERSION,
        "revision": SUITE_REVISION,
        "held_out_digest": suite.digest(split="held_out"),
        "scenarios": SCENARIOS,
    }

    print(f"scenarios      : {coverage.total}")
    print(f"splits         : {coverage.split_counts()}")
    print(f"adversarial    : {coverage.adversarial}")
    print(f"missing areas  : {coverage.missing_areas or 'none'}")
    print(f"held-out digest: {payload['held_out_digest'][:16]}…")
    for area, count in coverage.by_area:
        print(f"  {area:<24} {count}")

    if args.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        print(f"\nwrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
